"""Миграции на пустой базе: применяются, откатываются и совпадают с моделями.

Тесты синхронные: Alembic внутри env.py сам запускает asyncio.run().
"""

import asyncio

import asyncpg
import pytest
from alembic import command
from alembic.script import ScriptDirectory
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import make_url

from tests.conftest import alembic_config

APP_TABLES = {"users", "niches", "niche_queries", "user_niches"}


def tables(database_url: str) -> set[str]:
    async def fetch() -> set[str]:
        dsn = make_url(database_url).set(drivername="postgresql").render_as_string(hide_password=False)
        conn = await asyncpg.connect(dsn)
        try:
            rows = await conn.fetch("SELECT tablename FROM pg_tables WHERE schemaname = 'public'")
        finally:
            await conn.close()
        return {row["tablename"] for row in rows}

    return asyncio.run(fetch())


def revisions(database_url: str) -> list[str]:
    """Все миграции от первой к последней."""
    script = ScriptDirectory.from_config(alembic_config(database_url))
    return [revision.revision for revision in reversed(list(script.walk_revisions()))]


def test_upgrade_creates_tables_and_downgrade_removes_them(migrations_database_url: str):
    config = alembic_config(migrations_database_url)

    command.upgrade(config, "head")
    assert APP_TABLES <= tables(migrations_database_url)

    command.downgrade(config, "base")
    assert tables(migrations_database_url) == {"alembic_version"}


def test_models_match_migrations(migrations_database_url: str):
    """Изменили модель и забыли миграцию — тест падает. То же делает `make db-status`."""
    config = alembic_config(migrations_database_url)
    command.upgrade(config, "head")
    try:
        command.check(config)
    except AutogenerateDiffsDetected as exc:
        pytest.fail(f'Модели не совпадают с миграциями — запустите make migration m="...":\n{exc}')


def test_stairway(migrations_database_url: str):
    """Каждая миграция по очереди: вверх → вниз → снова вверх.

    Ловит забытый или неполный downgrade(): например, таблицу удалили, а индекс остался.
    """
    config = alembic_config(migrations_database_url)
    for revision in revisions(migrations_database_url):
        command.upgrade(config, revision)
        command.downgrade(config, "-1")
        command.upgrade(config, revision)


def test_revision_ids_are_sequential_numbers(migrations_database_url: str):
    """Номера миграций — 0001, 0002, …: так их создаёт make migration, и так их легко читать."""
    ids = revisions(migrations_database_url)
    assert ids == [f"{number:04d}" for number in range(1, len(ids) + 1)]
