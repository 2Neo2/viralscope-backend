"""Подключение к PostgreSQL: базовый класс моделей, движок, сессия на запрос.

Как это устроено:
- engine — пул соединений с базой. Один на приложение, создаётся в create_app и закрывается при остановке.
- sessionmaker — фабрика сессий. Сессия — «рабочий блокнот» запроса: копит изменения до commit().
- SessionDep — зависимость FastAPI: каждый запрос получает свою сессию, после ответа она закрывается.

Транзакции фиксирует код сервиса явным `await session.commit()`. Если commit не вызван или
случилась ошибка, при закрытии сессии изменения откатываются — в базу не попадёт половина операции.
"""

import re
import time
from collections.abc import AsyncGenerator
from datetime import UTC, datetime
from typing import Annotated, Any

from fastapi import Depends, Request
from sqlalchemy import BigInteger, DateTime, Identity, MetaData, event, func
from sqlalchemy.ext.asyncio import AsyncEngine, AsyncSession, async_sessionmaker, create_async_engine
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from app.core.config import Settings
from app.core.logging import get_logger

log = get_logger(__name__)

# Правила имён для индексов и ограничений. Без них PostgreSQL придумывает имена сам,
# и Alembic не может надёжно их найти, чтобы изменить или удалить в следующей миграции.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Базовый класс всех моделей. Base.metadata — схема всех таблиц, по ней Alembic строит миграции."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


def utcnow() -> datetime:
    """Текущее время в UTC с таймзоной. В базе храним timestamptz, показываем — в часовом поясе клиента."""
    return datetime.now(UTC)


# Первичный ключ: BIGINT GENERATED BY DEFAULT AS IDENTITY — современный автоинкремент PostgreSQL.
# BIGINT, а не INT: 2 млрд строк кажутся недостижимыми, пока не начнёшь хранить снимки метрик видео.
IntPK = Annotated[int, mapped_column(BigInteger, Identity(), primary_key=True)]


class CreatedAtMixin:
    """Колонка created_at со временем базы (now()), а не сервера приложения."""

    # sort_order: служебные колонки — в конце таблицы, после полей модели
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), sort_order=100
    )


class TimestampMixin(CreatedAtMixin):
    """created_at и updated_at.

    updated_at обновляется при изменении через ORM, ручной UPDATE в SQL его не трогает.
    """

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), sort_order=101
    )


def create_engine(settings: Settings) -> AsyncEngine:
    """Пул соединений. Соединения открываются лениво — при первом запросе, а не здесь."""
    engine = create_async_engine(
        settings.database_url,
        echo=settings.db_echo,
        pool_size=settings.db_pool_size,
        max_overflow=settings.db_max_overflow,
        pool_timeout=settings.db_pool_timeout,
        pool_pre_ping=True,  # проверить соединение перед выдачей: база могла перезапуститься
        pool_recycle=1800,  # пересоздавать соединения раз в 30 минут
        # Имя приложения видно в pg_stat_activity: понятно, кто держит соединения — api или worker
        connect_args={"server_settings": {"application_name": f"viralscope-{settings.service}"}},
    )
    if settings.db_slow_query_ms > 0:
        log_slow_queries(engine, settings.db_slow_query_ms)
    return engine


SLOW_QUERY_MAX_CHARS = 1000
_WHITESPACE = re.compile(r"\s+")


def log_slow_queries(engine: AsyncEngine, threshold_ms: int) -> None:
    """Писать в лог SQL-запросы дольше threshold_ms — событие slow_query (уровень warning).

    В лог идёт текст запроса с плейсхолдерами ($1, $2), но НЕ значения параметров:
    в них бывают почта, токены и другие личные данные.
    request_id подставляется сам (contextvars) — по нему видно, какой запрос API тормозил.
    """
    # События SQLAlchemy синхронные — вешаем их на sync_engine внутри AsyncEngine
    sync_engine = engine.sync_engine

    @event.listens_for(sync_engine, "before_cursor_execute")
    def start_timer(conn: Any, cursor: Any, statement: str, parameters: Any, context: Any, executemany: bool):
        conn.info.setdefault("query_started", []).append(time.perf_counter())

    @event.listens_for(sync_engine, "after_cursor_execute")
    def stop_timer(conn: Any, cursor: Any, statement: str, parameters: Any, context: Any, executemany: bool):
        duration_ms = (time.perf_counter() - conn.info["query_started"].pop()) * 1000
        if duration_ms < threshold_ms:
            return
        log.warning(
            "slow_query",
            duration_ms=round(duration_ms, 1),
            threshold_ms=threshold_ms,
            statement=_WHITESPACE.sub(" ", statement).strip()[:SLOW_QUERY_MAX_CHARS],
            rows=cursor.rowcount if cursor.rowcount >= 0 else None,
        )

    @event.listens_for(sync_engine, "handle_error")
    def drop_timer(context: Any) -> None:
        # Запрос упал — after_cursor_execute не вызовется, убираем его отметку времени
        if context.connection is not None and context.connection.info.get("query_started"):
            context.connection.info["query_started"].pop()


def create_sessionmaker(engine: AsyncEngine) -> async_sessionmaker[AsyncSession]:
    # expire_on_commit=False: после commit объекты остаются читаемыми без нового запроса в базу.
    # В async это обязательно — ленивая подгрузка после commit упала бы с ошибкой MissingGreenlet.
    return async_sessionmaker(engine, expire_on_commit=False)


async def get_session(request: Request) -> AsyncGenerator[AsyncSession, None]:
    """Зависимость FastAPI: одна сессия на один запрос, закрывается после ответа."""
    sessionmaker: async_sessionmaker[AsyncSession] = request.app.state.sessionmaker
    async with sessionmaker() as session:
        yield session


SessionDep = Annotated[AsyncSession, Depends(get_session)]
